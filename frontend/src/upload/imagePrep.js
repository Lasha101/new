// Client-side preparation of a document before it is uploaded: HEIC to JPEG,
// then downscale and re-encode. Browser-only — it needs canvas and
// createImageBitmap. The byte-level half is in fileSniff.js and runs anywhere.
//
// Why this exists: a phone photo is 3-5 Mo and 3-4000 px on the long edge. The
// MRZ is legible far below that, so uploading the original spends tens of
// seconds of 4G for nothing.
//
// The trap, and the reason this file is longer than it looks: canvas
// re-encoding silently discards EXIF. A portrait photo stored landscape with a
// rotation flag therefore reaches the OCR sideways, and a sideways MRZ does not
// read. Every decode below establishes, per file, whether the browser already
// applied the orientation, and applies it itself when the browser did not.
//
// Privacy: everything here is in memory. No document byte is written to Cache
// API, localStorage, sessionStorage or IndexedDB, and every object URL this
// module creates is revoked in a finally block before the function returns.

import {
    sniffFileType, readExifOrientation, readJpegDimensions, stripExifSegments,
    orientationTransform, swapsAxes, targetDimensions, replaceExtension,
} from './fileSniff.js';

/** Long edge, in pixels, of an uploaded image. An MRZ stays readable well below this. */
export const MAX_EDGE = 2500;

/** JPEG quality of the re-encode. */
export const JPEG_QUALITY = 0.85;

/**
 * Files at or below this size are uploaded byte-for-byte.
 *
 * 1 Mo crosses a 4G link in about a second, so re-encoding it would cost more
 * (decode + encode on a phone CPU) than it saves, and every re-encode is a
 * small loss of the detail the OCR reads. A file that needs rotating is
 * processed whatever its size — that is a correctness fix, not an optimisation.
 */
export const SKIP_BYTES = 1_000_000;

/** How much of a file we read to sniff its type, EXIF and stored dimensions. */
const HEAD_BYTES = 128 * 1024;

